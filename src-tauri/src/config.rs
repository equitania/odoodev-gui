use serde::Deserialize;

#[derive(Debug, Clone, Deserialize, Default)]
pub struct OdoodevConfig {
    pub active_versions: Option<Vec<String>>,
    #[serde(rename = "container_runtime")]
    pub container_runtime: Option<String>,
}

/// Read the global odoodev config at ~/.config/odoodev/config.yaml
pub fn read_config() -> Option<OdoodevConfig> {
    let home = crate::odoodev::home_dir();
    let candidates = [
        home.join(".config/odoodev/config.yaml"),
        home.join(".config/odoodev/config.yml"),
    ];
    for path in &candidates {
        if let Ok(content) = std::fs::read_to_string(path) {
            if let Ok(cfg) = serde_yaml::from_str::<OdoodevConfig>(&content) {
                return Some(cfg);
            }
        }
    }
    None
}

pub fn get_active_versions() -> Vec<String> {
    read_config()
        .and_then(|c| c.active_versions)
        .unwrap_or_default()
}

pub fn get_container_runtime() -> Option<String> {
    read_config().and_then(|c| c.container_runtime)
}

#[cfg(test)]
mod tests {
    use super::*;

    // Scrubbed shape of ~/.config/odoodev/config.yaml (extra keys must be ignored).
    const FULL: &str = "# Generated by: odoodev setup
base_dir: ~/gitbase
database:
  user: demo
  password: placeholder
cli:
  language: en
active_versions:
- '16'
- '18'
- '19'
container_runtime: apple
";

    #[test]
    fn parses_active_versions_and_runtime_ignoring_unknown_keys() {
        let cfg: OdoodevConfig = serde_yaml::from_str(FULL).unwrap();
        assert_eq!(
            cfg.active_versions.unwrap(),
            vec!["16".to_string(), "18".to_string(), "19".to_string()]
        );
        assert_eq!(cfg.container_runtime.as_deref(), Some("apple"));
    }

    #[test]
    fn missing_keys_are_none() {
        let cfg: OdoodevConfig = serde_yaml::from_str("cli:\n  language: de\n").unwrap();
        assert!(cfg.active_versions.is_none());
        assert!(cfg.container_runtime.is_none());
    }

    #[test]
    fn empty_document_is_default_or_error_not_panic() {
        // An empty file is valid YAML (null); serde_yaml may reject it for a struct.
        let r = serde_yaml::from_str::<OdoodevConfig>("");
        if let Ok(cfg) = r {
            assert!(cfg.active_versions.is_none());
        }
    }

    #[test]
    fn unknown_runtime_value_is_kept_verbatim() {
        let cfg: OdoodevConfig = serde_yaml::from_str("container_runtime: podman\n").unwrap();
        assert_eq!(cfg.container_runtime.as_deref(), Some("podman"));
    }

    #[test]
    fn malformed_yaml_is_an_error() {
        assert!(serde_yaml::from_str::<OdoodevConfig>("active_versions: [unclosed\n").is_err());
        // wrong type for a known field
        assert!(serde_yaml::from_str::<OdoodevConfig>("active_versions: notalist\n").is_err());
    }
}
